#!/usr/bin/env bash
# Verify or update the committed generated fixtures.
#
# Generation is always staged in a temp dir, so a broken template fails before
# the tree is touched and a local fixture edit is never silently replaced.
#
# A row is <generator>|<plugin pkg>|<proto dir>|<out flag>|<fixture dir>|<glob>.
# protoc is pinned in .mise.toml because its version lands in the generated
# header: an unpinned one reports drift that is not real.
set -uo pipefail

root="$(git rev-parse --show-toplevel 2>/dev/null)" || {
  echo "generated-fixtures: not inside a git checkout" >&2
  exit 1
}
cd "$root" || exit 1

rows=(
  "govalidator|./protobuf/protoc-gen-govalidator|protobuf/protoc-gen-govalidator/valtest|govalidator_out|protobuf/protoc-gen-govalidator/valtest|*.validator*.pb.go"
  "govalidator|./protobuf/protoc-gen-govalidator|protobuf/protoc-gen-govalidator/example|govalidator_out|protobuf/protoc-gen-govalidator/example|*.validator*.pb.go"
  "s12perm|./protobuf/protoc-gen-s12perm|protobuf/protoc-gen-s12perm/example|s12perm_out|protobuf/protoc-gen-s12perm/example|*.perm.pb.go"
)

# Committed output this script does not regenerate, so an omission reads as a
# decision; move an entry into `rows` to cover it.
readonly uncovered='Not covered:
  go             protoc-gen-go output under s12/ — needs a re-baseline and a pin first
  gogo           protoc-gen-gogo is not installed by .mise.toml
  cruxclient     C++ output, generated by hand via the Makefile targets
  cruxclient-go  Swift/Kotlin goldens, covered by the native-evidence CI job'

usage() {
  cat <<'EOF'
usage: generated-fixtures.sh <mode> [generator…]

  verify [generator…]   compare the tree with a fresh generation; writes nothing,
                        exits 1 on drift
  update [generator…]   apply a fresh generation to the tree (adds, updates and
                        removes that generator's fixtures)
  list                  show the declared generators and what is not covered

Generators are declared in the `rows` array; adding one is a single row.
With no generator named, every declared row runs.
EOF
}

die() {
  printf 'generated-fixtures: %s\n' "$*" >&2
  exit 1
}

# stage <row> <dir> — build the plugin and generate its protos into <dir>/gen.
stage() {
  local row="$1" work="$2"
  local name plugin protodir flag
  IFS='|' read -r name plugin protodir flag _ <<<"$row"

  mkdir -p "$work/bin" "$work/gen" || return 1
  if ! go build -o "$work/bin/plugin" "$plugin" >"$work/build.log" 2>&1; then
    printf '  %s failed to build:\n' "$plugin"
    sed 's/^/    /' "$work/build.log"
    return 1
  fi

  local plugname="${flag%_out}"
  # shellcheck disable=SC2086  # the glob must expand
  if ! protoc -I"$protodir" -I. \
    --plugin="protoc-gen-$plugname=$work/bin/plugin" \
    --"$flag"=paths=source_relative:"$work/gen" \
    "$protodir"/*.proto >"$work/protoc.log" 2>&1; then
    printf '  protoc failed for %s:\n' "$protodir"
    sed 's/^/    /' "$work/protoc.log"
    return 1
  fi
}

# committed <fixture dir> <glob> — the fixtures the repo tracks for a row.
committed() {
  git ls-files -- ":(glob)$1/$2" | sort
}

# compare <row> <dir> — report drift; `quiet` (update) suppresses the report.
compare() {
  local row="$1" work="$2"
  local fixtures glob path base drift=0
  IFS='|' read -r _ _ _ _ fixtures glob <<<"$row"

  # shellcheck disable=SC2046
  for path in $(cd "$work/gen" && ls -1); do
    if [ ! -f "$fixtures/$path" ]; then
      [ "$quiet" = 0 ] && printf '    added      %s\n' "$fixtures/$path"
      drift=1
    elif ! cmp -s "$work/gen/$path" "$fixtures/$path"; then
      if [ "$quiet" = 0 ]; then
        printf '    changed    %s\n' "$fixtures/$path"
        diff -u --label "committed/$path" --label "regenerated/$path" \
          "$fixtures/$path" "$work/gen/$path" | sed -n '3,42p' | sed 's/^/      /'
      fi
      drift=1
    fi
  done

  # shellcheck disable=SC2046
  for path in $(committed "$fixtures" "$glob"); do
    base="$(basename "$path")"
    if [ ! -e "$work/gen/$base" ]; then
      [ "$quiet" = 0 ] && printf '    stale      %s\n' "$path"
      drift=1
    fi
  done

  return "$drift"
}

# apply <row> <dir> — copy the staged output over the tree, dropping stale files.
apply() {
  local row="$1" work="$2"
  local fixtures glob path base
  IFS='|' read -r _ _ _ _ fixtures glob <<<"$row"

  # shellcheck disable=SC2046
  for path in $(cd "$work/gen" && ls -1); do
    if [ ! -f "$fixtures/$path" ]; then
      printf '    added      %s\n' "$fixtures/$path"
    elif cmp -s "$work/gen/$path" "$fixtures/$path"; then
      continue
    else
      printf '    updated    %s\n' "$fixtures/$path"
    fi
    cp "$work/gen/$path" "$fixtures/$path" || return 1
  done

  # shellcheck disable=SC2046
  for path in $(committed "$fixtures" "$glob"); do
    base="$(basename "$path")"
    if [ ! -e "$work/gen/$base" ]; then
      printf '    removed    %s\n' "$path"
      rm -f "$path" || return 1
    fi
  done
}

# selected <name> — true when no generator was named, or this one was.
# `wanted` is space-delimited so bash 3.2 keeps an empty one defined under -u.
selected() {
  case "$wanted" in
    "") return 0 ;;
    *" $1 "*) return 0 ;;
  esac
  return 1
}

main() {
  local mode="${1:-}"
  [ -n "$mode" ] && shift

  case "$mode" in
    -h | --help) usage; return 0 ;;
    verify | update | list) ;;
    "") usage >&2; return 2 ;;
    *) die "unknown mode '$mode' (want verify, update or list)" ;;
  esac

  local known="" row name entry known_one
  for row in "${rows[@]}"; do
    name="${row%%|*}"
    case " $known " in *" $name "*) continue ;; esac
    known="${known:+$known }$name"
  done

  if [ "$mode" = list ]; then
    local protodir fixtures glob
    for row in "${rows[@]}"; do
      IFS='|' read -r name _ protodir _ fixtures glob <<<"$row"
      printf '%-12s %-46s %s\n' "$name" "$protodir" "$fixtures/$glob"
    done
    printf '\n%s\n' "$uncovered"
    return 0
  fi

  wanted=""
  for entry in "$@"; do
    known_one=0
    case " $known " in *" $entry "*) known_one=1 ;; esac
    [ "$known_one" = 1 ] || die "unknown generator '$entry' (one of:$known)"
    wanted="$wanted $entry "
  done
  # `tmp` is global: the EXIT trap outlives main's locals.
  tmp="$(mktemp -d)"
  trap 'rm -rf "${tmp:-}"' EXIT

  # Bash 3.2: index with a counter rather than expanding a possibly-empty array.
  local staged_rows=() staged_dirs=() n=0 i=0 drift=0 idx
  quiet=0
  [ "$mode" = update ] && quiet=1
  for row in "${rows[@]}"; do
    name="${row%%|*}"
    selected "$name" || continue
    i=$((i + 1))
    # Staging every row before comparing or applying: a failure here leaves the
    # tree untouched.
    stage "$row" "$tmp/$i" || return 1
    staged_rows[$n]="$row"
    staged_dirs[$n]="$tmp/$i"
    n=$((n + 1))
  done

  # A typo in the filter must fail loudly: zero rows would otherwise read as a
  # clean tree.
  [ "$n" -gt 0 ] || die "no generators matched '${wanted# }'"
  idx=0
  while [ "$idx" -lt "$n" ]; do
    row="${staged_rows[$idx]}"
    IFS='|' read -r name _ protodir _ _ _ <<<"$row"
    [ "$quiet" = 0 ] && printf '%-12s %s\n' "$name" "$protodir"
    if compare "$row" "${staged_dirs[$idx]}"; then
      [ "$quiet" = 0 ] && printf '    ok\n'
    else
      drift=1
    fi
    idx=$((idx + 1))
  done

  if [ "$mode" = update ]; then
    idx=0
    while [ "$idx" -lt "$n" ]; do
      row="${staged_rows[$idx]}"
      IFS='|' read -r name _ protodir _ _ _ <<<"$row"
      printf '%-12s %s\n' "$name" "$protodir"
      apply "$row" "${staged_dirs[$idx]}" || die "failed to update the tree"
      idx=$((idx + 1))
    done
    [ "$drift" = 0 ] && printf '\nAlready up to date.\n'
    return 0
  fi

  [ "$drift" = 0 ] && return 0
  printf '\nThe committed fixtures differ from a fresh generation.\n' >&2
  printf "Run 'mise run update:generated' and commit the result.\n" >&2
  return 1
}

main "$@"
