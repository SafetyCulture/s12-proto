// Standard library dependencies.
const (
	contextPackage = protogen.GoImportPath("context")
	logPackage     = protogen.GoImportPath("log")
)

// Other library dependencies.
const (
	grpcPackage        = protogen.GoImportPath("google.golang.org/grpc")
	grpccodesPackage   = protogen.GoImportPath("google.golang.org/grpc/codes")
	grpcstatusPackage  = protogen.GoImportPath("google.golang.org/grpc/status")
	s12permPackage     = protogen.GoImportPath("github.com/SafetyCulture/s12-proto/s12/flags/permissions")
	jwtclaimsPackage   = protogen.GoImportPath("sc-go.io/pkg/jwtclaims")
	credentialsPackage = protogen.GoImportPath("sc-go.io/pkg/credentials")
)

// GenerateFile generates the .perm.pb.go file
func GenerateFile(p *protogen.Plugin, file *protogen.File) *protogen.GeneratedFile {
	if len(file.Services) == 0 {
		return nil
	}

	if err := validateRequiredPermissions(file); err != nil {
		p.Error(err)
		return nil
	}

	filename := file.GeneratedFilenamePrefix + ".perm.pb.go"
	g := p.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-govalidator. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	// blank import to register extension for gRPC Reflection API
	g.Import(s12permPackage)

	for _, srv := range file.Services {
		genSrvInterceptor(g, srv)
	}

	return g
}

func genSrvInterceptor(g *protogen.GeneratedFile, srv *protogen.Service) {
	genUnaryInterceptor(g, srv)
	genStreamInterceptor(g, srv)
}

func genUnaryInterceptor(g *protogen.GeneratedFile, srv *protogen.Service) {
	g.P("// ", srv.GoName, "PermissionsUnaryInterceptor is a gRPC unary server interceptor that validates the S12 JWT claims")
	g.P("// for defined permissions for a service method. Returns PermissionDenied status on permission error.")
	g.P("func ", srv.GoName, "PermissionsUnaryInterceptor() ", grpcPackage.Ident("UnaryServerInterceptor"), " {")
	g.P("return func(ctx ", contextPackage.Ident("Context"), ", req interface{}, info *", grpcPackage.Ident("UnaryServerInfo"), ", handler ", grpcPackage.Ident("UnaryHandler"), ") (interface{}, error) {")
	g.P("c, _ := ctx.Value(", jwtclaimsPackage.Ident("ContextKeyS12JWTClaims"), ").(", jwtclaimsPackage.Ident("S12JWTClaims"), ")")
	g.P("_ = c")

	g.P("scopes, _ := ctx.Value(", credentialsPackage.Ident("ContextKeyCredentialsScope"), ").(", credentialsPackage.Ident("Scope"), ")")
	g.P("_ = scopes")

	for _, md := range srv.Methods {
		if md.Desc.IsStreamingClient() || md.Desc.IsStreamingServer() {
			continue
		}
		flags := getStringSliceExtension(md, permissions.E_RequiredFlags)
		reqs := getPermissionRequirements(md)
		scopeFlag := getStringExtension(md, permissions.E_RequiredScope)
		if len(flags) == 0 && len(reqs) == 0 && scopeFlag == "" {
			continue
		}

		sname := fmt.Sprintf("/%s/%s", srv.Desc.FullName(), md.Desc.Name())
		g.P("if info.FullMethod == \"", sname, "\" {")
		if len(flags) > 0 {
			var perms []string
			for _, perm := range flags {
				perms = append(perms, fmt.Sprintf("%s(%q)", g.QualifiedGoIdent(jwtclaimsPackage.Ident("Permission")), perm))
			}
			g.P("if !scopes.IsAdmin() && !c.HasPermission(", strings.Join(perms, ", "), ") {")
			g.P(logPackage.Ident("Println"), "(\"s12perm: claims does not contain the required permissions\")")
			g.P("return ctx, ", grpcstatusPackage.Ident("Errorf"), "(", grpccodesPackage.Ident("PermissionDenied"), ", ", "\"Permission Denied\"", ")")
			g.P("}")
		}

		if len(reqs) > 0 {
			g.P("if !scopes.IsAdmin() && !(", permissionRequirementsExpr(g, reqs), ") {")
			g.P(logPackage.Ident("Println"), "(\"s12perm: claims does not satisfy the required permissions\")")
			g.P("return ctx, ", grpcstatusPackage.Ident("Errorf"), "(", grpccodesPackage.Ident("PermissionDenied"), ", ", "\"Permission Denied\"", ")")
			g.P("}")
		}

		if scopeFlag != "" {
			g.P("if !scopes.Contains(", fmt.Sprintf("%q", scopeFlag), ") {")
			g.P(logPackage.Ident("Println"), "(\"s12perm: claims does not contain the required scopes\")")
			g.P("return ctx, ", grpcstatusPackage.Ident("Errorf"), "(", grpccodesPackage.Ident("PermissionDenied"), ", ", "\"Permission Denied\"", ")")
			g.P("}")
		}

		g.P("}") // end if
	}

	g.P("return handler(ctx, req)")
	g.P("}")
	g.P("}")
	g.P()
}

func genStreamInterceptor(g *protogen.GeneratedFile, srv *protogen.Service) {
	g.P("// ", srv.GoName, "PermissionsStreamInterceptor is a gRPC stream server interceptor that validates the S12 JWT claims")
	g.P("// for defined permissions for a service method. Returns PermissionDenied status on permission error.")
	g.P("func ", srv.GoName, "PermissionsStreamInterceptor() ", grpcPackage.Ident("StreamServerInterceptor"), " {")
	g.P("return func(srv interface{}, stream ", grpcPackage.Ident("ServerStream"), ", info *", grpcPackage.Ident("StreamServerInfo"), ", handler ", grpcPackage.Ident("StreamHandler"), ") error {")
	g.P("c, _ := stream.Context().Value(", jwtclaimsPackage.Ident("ContextKeyS12JWTClaims"), ").(", jwtclaimsPackage.Ident("S12JWTClaims"), ")")
	g.P("_ = c")

	g.P("scopes, _ := stream.Context().Value(", credentialsPackage.Ident("ContextKeyCredentialsScope"), ").(", credentialsPackage.Ident("Scope"), ")")
	g.P("_ = scopes")
	// (rogchap) A lot of this is repeated from the unary interceptor; a refactor to make this more DRY
	// is possible, however it would remove some of the readability, so keeping the repetition.
	for _, md := range srv.Methods {
		if !md.Desc.IsStreamingClient() && !md.Desc.IsStreamingServer() {
			continue
		}
		flags := getStringSliceExtension(md, permissions.E_RequiredFlags)
		reqs := getPermissionRequirements(md)
		scopeFlag := getStringExtension(md, permissions.E_RequiredScope)
		if len(flags) == 0 && len(reqs) == 0 && scopeFlag == "" {
			continue
		}

		sname := fmt.Sprintf("/%s/%s", srv.Desc.FullName(), md.Desc.Name())
		g.P("if info.FullMethod == \"", sname, "\" {")
		if len(flags) > 0 {
			var perms []string
			for _, perm := range flags {
				perms = append(perms, fmt.Sprintf("%s(%q)", g.QualifiedGoIdent(jwtclaimsPackage.Ident("Permission")), perm))
			}
			g.P("if !scopes.IsAdmin() && !c.HasPermission(", strings.Join(perms, ", "), ") {")
			g.P(logPackage.Ident("Println"), "(\"s12perm: claims does not contain the required permissions\")")
			g.P("return ", grpcstatusPackage.Ident("Errorf"), "(", grpccodesPackage.Ident("PermissionDenied"), ", ", "\"Permission Denied\"", ")")
			g.P("}")
		}

		if len(reqs) > 0 {
			g.P("if !scopes.IsAdmin() && !(", permissionRequirementsExpr(g, reqs), ") {")
			g.P(logPackage.Ident("Println"), "(\"s12perm: claims does not satisfy the required permissions\")")
			g.P("return ", grpcstatusPackage.Ident("Errorf"), "(", grpccodesPackage.Ident("PermissionDenied"), ", ", "\"Permission Denied\"", ")")
			g.P("}")
		}

		if scopeFlag != "" {
			g.P("if !scopes.Contains(", fmt.Sprintf("%q", scopeFlag), ") {")
			g.P(logPackage.Ident("Println"), "(\"s12perm: claims does not contain the required scopes\")")
			g.P("return ", grpcstatusPackage.Ident("Errorf"), "(", grpccodesPackage.Ident("PermissionDenied"), ", ", "\"Permission Denied\"", ")")
			g.P("}")
		}
		g.P("}")
	}

	g.P("return handler(srv, stream)")
	g.P("}")
	g.P("}")
	g.P()
}

// permissionRequirementsExpr builds a Go boolean expression that is true when the claims
// satisfy every requirement. HasPermission is variadic over a conjunction, so an all_of
// requirement is one call while an any_of requirement needs a call per permission.
func permissionRequirementsExpr(g *protogen.GeneratedFile, reqs []*permissions.PermissionRequirement) string {
	terms := make([]string, 0, len(reqs))
	for _, req := range reqs {
		if allOf := req.GetAllOf(); len(allOf) > 0 {
			terms = append(terms, fmt.Sprintf("c.HasPermission(%s)", strings.Join(permissionArgs(g, allOf), ", ")))
			continue
		}
		checks := make([]string, 0, len(req.GetAnyOf()))
		for _, arg := range permissionArgs(g, req.GetAnyOf()) {
			checks = append(checks, fmt.Sprintf("c.HasPermission(%s)", arg))
		}
		if len(checks) > 1 {
			terms = append(terms, "("+strings.Join(checks, " || ")+")")
			continue
		}
		terms = append(terms, checks...)
	}
	return strings.Join(terms, " && ")
}

func permissionArgs(g *protogen.GeneratedFile, perms []string) []string {
	args := make([]string, 0, len(perms))
	for _, perm := range perms {
		args = append(args, fmt.Sprintf("%s(%q)", g.QualifiedGoIdent(jwtclaimsPackage.Ident("Permission")), perm))
	}
	return args
}

// validateRequiredPermissions rejects a requirement naming both operators or neither,
// so that every requirement has one unambiguous reading.
func validateRequiredPermissions(file *protogen.File) error {
	for _, srv := range file.Services {
		for _, md := range srv.Methods {
			for _, req := range getPermissionRequirements(md) {
				switch {
				case len(req.GetAnyOf()) > 0 && len(req.GetAllOf()) > 0:
					return fmt.Errorf("%s.%s: a required_permissions entry sets both any_of and all_of; declare one entry per operator",
						srv.Desc.FullName(), md.Desc.Name())
				case len(req.GetAnyOf()) == 0 && len(req.GetAllOf()) == 0:
					return fmt.Errorf("%s.%s: a required_permissions entry sets neither any_of nor all_of",
						srv.Desc.FullName(), md.Desc.Name())
				}
			}
		}
	}
	return nil
}

func getPermissionRequirements(md *protogen.Method) []*permissions.PermissionRequirement {
	if opts := md.Desc.Options(); opts != nil {
		ext := proto.GetExtension(opts, permissions.E_RequiredPermissions)
		if v, ok := ext.([]*permissions.PermissionRequirement); ok {
			return v
		}
	}
	return nil
}

func getStringSliceExtension(md *protogen.Method, xt protoreflect.ExtensionType) []string {
	if opts := md.Desc.Options(); opts != nil {
		ext := proto.GetExtension(opts, xt)
		if v, ok := ext.([]string); ok {
			return v
		}
	}
	return nil
}
func getStringExtension(md *protogen.Method, xt protoreflect.ExtensionType) string {
	if opts := md.Desc.Options(); opts != nil {
		ext := proto.GetExtension(opts, xt)
		if v, ok := ext.(string); ok {
			return v
		}
	}
	return ""
}
