//go:embed runtime/S12Wire.kt
var runtimeSource string

const runtimePackage = "com.safetyculture.s12kt.wire"

// RuntimeFileName returns the path of the runtime file for a root package.
func RuntimeFileName(root string) string {
	return strings.ReplaceAll(root, ".", "/") + "/wire/S12Wire.kt"
}

// KeepRulesFileName returns the path of the shrinker keep rules for a root package.
func KeepRulesFileName(root string) string {
	return strings.ReplaceAll(root, ".", "/") + "/s12kt.pro"
}

// keepRulesFor returns the shrinker rules that keep the methods the JNI translator calls by name.
func keepRulesFor(root string) string {
	return "-keep class " + root + ".** {\n" +
		"    public static ** parseFrom(byte[]);\n" +
		"    public byte[] toByteArray();\n" +
		"    public int getSerializedSize();\n" +
		"}\n"
}

// runtimeFor returns the runtime source for a root package.
func runtimeFor(root string) string {
	return strings.Replace(runtimeSource, "package "+runtimePackage+"\n", "package "+escapePackage(root)+".wire\n", 1)
}

// FileName returns the path of the Kotlin file of a proto file: the directory of its Kotlin
// package, then the name of the proto file.
func FileName(file protoreflect.FileDescriptor, root string) string {
	base := strings.TrimSuffix(path.Base(string(file.Path())), ".proto")
	return strings.ReplaceAll(kotlinPackage(file, root), ".", "/") + "/" + base + ".pb.kt"
}

// Generate writes one .pb.kt file for each proto file that has a message or an enum,
// the runtime file once, and the keep rules once.
func Generate(rw protoplugin.ResponseWriter, files []protoreflect.FileDescriptor, root string) error {
	if err := ValidateRoot(root); err != nil {
		return err
	}
	packageNames := map[string]map[string]string{}
	for _, file := range files {
		if file.Messages().Len() == 0 && file.Enums().Len() == 0 {
			continue
		}
		kotlinPackage := kotlinPackage(file, root)
		names := packageNames[kotlinPackage]
		if names == nil {
			names = map[string]string{}
			packageNames[kotlinPackage] = names
		}
		enums := file.Enums()
		for i := range enums.Len() {
			e := enums.Get(i)
			if err := checkKotlinName(names, string(e.Name()), escapeIdent(classNameForRoot(string(e.Name()), root))); err != nil {
				return fmt.Errorf("%s: %w", file.Path(), err)
			}
		}
		messages := file.Messages()
		for i := range messages.Len() {
			m := messages.Get(i)
			if err := checkKotlinName(names, string(m.Name()), escapeIdent(classNameForRoot(string(m.Name()), root))); err != nil {
				return fmt.Errorf("%s: %w", file.Path(), err)
			}
		}
	}

	wrote := false
	written := map[string]protoreflect.FileDescriptor{}
	for _, file := range files {
		if file.Messages().Len() == 0 && file.Enums().Len() == 0 {
			continue
		}
		content, err := GenerateFile(file, root)
		if err != nil {
			return fmt.Errorf("%s: %w", file.Path(), err)
		}
		name := FileName(file, root)
		if other, ok := written[name]; ok {
			return fmt.Errorf("%s and %s are in the same package and have the same file name", other.Path(), file.Path())
		}
		written[name] = file
		rw.AddFile(name, content)
		wrote = true
	}
	if wrote {
		rw.AddFile(RuntimeFileName(root), runtimeFor(root))
		rw.AddFile(KeepRulesFileName(root), keepRulesFor(root))
	}
	return nil
}

// GenerateFile returns the Kotlin source for one proto file.
func GenerateFile(file protoreflect.FileDescriptor, root string) (string, error) {
	fileNames := map[string]string{}
	enums := file.Enums()
	for i := range enums.Len() {
		e := enums.Get(i)
		if err := checkKotlinName(fileNames, string(e.Name()), escapeIdent(classNameForRoot(string(e.Name()), root))); err != nil {
			return "", err
		}
	}
	msgs := file.Messages()
	for i := range msgs.Len() {
		m := msgs.Get(i)
		if err := checkKotlinName(fileNames, string(m.Name()), escapeIdent(classNameForRoot(string(m.Name()), root))); err != nil {
			return "", err
		}
	}

	g := &fileGen{root: root, file: file}
	g.w.line("// Generated by protoc-gen-cruxclient-go. DO NOT EDIT.")
	g.w.line("// source: %s", file.Path())
	g.w.line("")
	g.w.line("package %s", escapePackage(kotlinPackage(file, root)))
	g.w.line("")
	for i := range enums.Len() {
		if err := g.enum(enums.Get(i)); err != nil {
			return "", err
		}
		g.w.line("")
	}
	for i := range msgs.Len() {
		if err := g.message(msgs.Get(i)); err != nil {
			return "", err
		}
		g.w.line("")
	}
	return strings.TrimRight(g.w.String(), "\n") + "\n", nil
}

type fileGen struct {
	root       string
	file       protoreflect.FileDescriptor
	w          writer
	needsCheck map[protoreflect.FullName]bool // see needsRequiredCheck
}

// rt returns the qualified name of a runtime type.
func (g *fileGen) rt(name string) string {
	return escapePackage(g.root) + ".wire." + name
}

func (g *fileGen) comment(d protoreflect.Descriptor) {
	g.w.doc(g.file.SourceLocations().ByDescriptor(d).LeadingComments)
}

func (g *fileGen) enum(e protoreflect.EnumDescriptor) error {
	name := escapeIdent(classNameForRoot(string(e.Name()), g.root))
	g.comment(e)
	g.w.open("public sealed class %s(override val number: kotlin.Int, public val name: kotlin.String) : %s {", name, g.rt("WireEnum"))
	values := e.Values()
	first := map[protoreflect.EnumNumber]string{}
	names := map[string]string{}
	var order []protoreflect.EnumNumber
	var aliases [][2]string
	var entries []string
	for i := 0; i < values.Len(); i++ {
		v := values.Get(i)
		entry := entryName(string(v.Name()))
		if err := checkKotlinName(names, string(v.Name()), entry); err != nil {
			return err
		}
		if canonical, ok := first[v.Number()]; ok {
			aliases = append(aliases, [2]string{entry, canonical})
			continue
		}
		first[v.Number()] = entry
		order = append(order, v.Number())
		entries = append(entries, entry)
		g.comment(v)
		g.w.line("public object %s : %s(%d, %s)", entry, name, v.Number(), kotlinString(string(v.Name())))
	}
	g.w.line("")
	g.w.line("/** A number that this version of the schema does not know. Get it from fromNumber. */")
	g.w.open("public class UNRECOGNIZED internal constructor(number: kotlin.Int) : %s(number, \"UNRECOGNIZED\") {", name)
	g.w.line("override fun equals(other: kotlin.Any?): kotlin.Boolean = other is UNRECOGNIZED && other.number == number")
	g.w.line("")
	g.w.line("override fun hashCode(): kotlin.Int = number")
	g.w.line("")
	g.w.line("override fun toString(): kotlin.String = \"UNRECOGNIZED($number)\"")
	g.w.close("}")
	g.w.line("")
	g.w.line("override fun toString(): kotlin.String = name")
	g.w.line("")
	g.w.open("public companion object {")
	for _, al := range aliases {
		g.w.line("public val %s: %s get() = %s", al[0], name, al[1])
	}
	if len(aliases) > 0 {
		g.w.line("")
	}
	g.w.line("@kotlin.jvm.JvmStatic")
	g.w.line("public val entries: kotlin.collections.List<%s> by lazy { kotlin.collections.listOf(%s) }", name, strings.Join(entries, ", "))
	g.w.line("")
	g.w.line("@kotlin.jvm.JvmStatic")
	g.w.open("public fun fromNumber(number: kotlin.Int): %s = when (number) {", name)
	for _, n := range order {
		g.w.line("%d -> %s", n, first[n])
	}
	g.w.line("else -> UNRECOGNIZED(number)")
	g.w.close("}")
	g.w.close("}")
	g.w.close("}")
	return nil
}

func checkKotlinName(names map[string]string, protoName, kotlinName string) error {
	if first, ok := names[kotlinName]; ok {
		return fmt.Errorf("%s and %s map to the same Kotlin name %q", first, protoName, kotlinName)
	}
	names[kotlinName] = protoName
	return nil
}

// oneofInfo describes a oneof of a message.
type oneofInfo struct {
	od     protoreflect.OneofDescriptor
	prop   string
	class  string // simple class name of the sealed class
	fields []*fieldInfo
}

// hasMessage reports whether a member of the oneof is a message.
func (o *oneofInfo) hasMessage() bool {
	for _, f := range o.fields {
		if f.fd.Message() != nil {
			return true
		}
	}
	return false
}

// fieldInfo describes one field of a message.
type fieldInfo struct {
	fd     protoreflect.FieldDescriptor
	prop   string
	oneof  *oneofInfo
	member string // class name of the oneof member
	reqBit int    // bit of a required field in the missing-required mask, or -1
}

func (f *fieldInfo) number() protoreflect.FieldNumber { return f.fd.Number() }

// nullable reports whether the property is nullable because the field tracks explicit presence.
func (f *fieldInfo) nullable() bool {
	fd := f.fd
	if f.oneof != nil || fd.IsList() || fd.IsMap() {
		return false
	}
	if fd.Message() != nil {
		return fd.Cardinality() != protoreflect.Required
	}
	return fd.HasPresence() && fd.Cardinality() != protoreflect.Required
}

// oneofClassNames returns the name of the sealed class of each oneof of a message. A oneof class
// takes a name that no nested declaration, no companion object and no earlier oneof class has.
func oneofClassNames(msg protoreflect.MessageDescriptor) map[protoreflect.OneofDescriptor]string {
	used := map[string]bool{"Companion": true}
	nested := msg.Messages()
	for i := 0; i < nested.Len(); i++ {
		used[className(string(nested.Get(i).Name()))] = true
	}
	enums := msg.Enums()
	for i := 0; i < enums.Len(); i++ {
		used[className(string(enums.Get(i).Name()))] = true
	}
	classes := map[protoreflect.OneofDescriptor]string{}
	fields := msg.Fields()
	for i := 0; i < fields.Len(); i++ {
		od := fields.Get(i).ContainingOneof()
		if od == nil || od.IsSynthetic() {
			continue
		}
		if _, ok := classes[od]; ok {
			continue
		}
		class := upperCamel(string(od.Name()))
		for used[class] {
			class += "Oneof"
		}
		used[class] = true
		classes[od] = class
	}
	return classes
}

// oneofMemberName returns the name of the class of a oneof member inside the sealed class.
func oneofMemberName(fd protoreflect.FieldDescriptor, class string) string {
	member := upperCamel(string(fd.Name()))
	if member == class || member == "Companion" {
		member += "Value"
	}
	return member
}

// OneofClass returns the simple name of the sealed class of a oneof.
func OneofClass(od protoreflect.OneofDescriptor) string {
	return oneofClassNames(od.Parent().(protoreflect.MessageDescriptor))[od]
}

// OneofMember returns the simple name of the class of a oneof member.
func OneofMember(fd protoreflect.FieldDescriptor) string {
	return oneofMemberName(fd, OneofClass(fd.ContainingOneof()))
}

// hasDeclaredDefault reports whether the field tracks presence and the schema declares a default for it.
// Its property is null when the field is not set, so the default is a constant of the companion object.
func (f *fieldInfo) hasDeclaredDefault() bool {
	return f.nullable() && f.fd.Message() == nil && f.fd.HasDefault()
}

func (g *fileGen) elementType(fd protoreflect.FieldDescriptor) string {
	switch fd.Kind() {
	case protoreflect.MessageKind, protoreflect.GroupKind:
		return QualifiedClassName(fd.Message(), g.root)
	case protoreflect.EnumKind:
		return QualifiedClassName(fd.Enum(), g.root)
	case protoreflect.BytesKind:
		return g.rt("ByteString")
	}
	return scalarType(fd.Kind())
}

func (g *fileGen) propertyType(f *fieldInfo) string {
	fd := f.fd
	switch {
	case fd.IsMap():
		return fmt.Sprintf("kotlin.collections.Map<%s, %s>", g.elementType(fd.MapKey()), g.elementType(fd.MapValue()))
	case fd.IsList():
		return "kotlin.collections.List<" + g.elementType(fd) + ">"
	case f.nullable():
		return g.elementType(fd) + "?"
	}
	return g.elementType(fd)
}

func (g *fileGen) propertyDefault(f *fieldInfo) string {
	fd := f.fd
	switch {
	case fd.IsMap():
		return "kotlin.collections.emptyMap()"
	case fd.IsList():
		return "kotlin.collections.emptyList()"
	case f.nullable():
		return "null"
	}
	return g.defaultLiteral(fd)
}

func (g *fileGen) message(msg protoreflect.MessageDescriptor) error {
	if msg.IsMapEntry() {
		return nil
	}
	name := escapeIdent(classNameForRoot(string(msg.Name()), g.root))
	qualified := QualifiedClassName(msg, g.root)

	nested := msg.Messages()
	enums := msg.Enums()
	oneofClasses := oneofClassNames(msg)
	classNames := map[string]string{}
	for i := range nested.Len() {
		m := nested.Get(i)
		if m.IsMapEntry() {
			continue
		}
		if err := checkKotlinName(classNames, string(m.Name()), escapeIdent(classNameForRoot(string(m.Name()), g.root))); err != nil {
			return err
		}
	}
	for i := range enums.Len() {
		e := enums.Get(i)
		if err := checkKotlinName(classNames, string(e.Name()), escapeIdent(classNameForRoot(string(e.Name()), g.root))); err != nil {
			return err
		}
	}
	seenOneofs := map[protoreflect.OneofDescriptor]bool{}
	fieldsForClasses := msg.Fields()
	for i := range fieldsForClasses.Len() {
		od := fieldsForClasses.Get(i).ContainingOneof()
		if od == nil || od.IsSynthetic() || seenOneofs[od] {
			continue
		}
		seenOneofs[od] = true
		if err := checkKotlinName(classNames, string(od.Name()), escapeIdent(oneofClasses[od])); err != nil {
			return err
		}
	}

	var fields, required []*fieldInfo
	oneofs := map[protoreflect.OneofDescriptor]*oneofInfo{}
	var oneofOrder []*oneofInfo
	emittedNames := map[string]string{}
	memberNames := map[protoreflect.OneofDescriptor]map[string]string{}
	fds := msg.Fields()
	for i := 0; i < fds.Len(); i++ {
		fd := fds.Get(i)
		if fd.Kind() == protoreflect.GroupKind {
			return fmt.Errorf("%s: group fields are not supported", fd.FullName())
		}
		f := &fieldInfo{fd: fd, prop: g.propertyName(fd), reqBit: -1}
		if od := fd.ContainingOneof(); od != nil && !od.IsSynthetic() {
			oi := oneofs[od]
			if oi == nil {
				oi = &oneofInfo{od: od, prop: g.oneofPropertyName(od), class: oneofClasses[od]}
				if err := checkKotlinName(emittedNames, string(od.Name()), oi.prop); err != nil {
					return err
				}
				oneofs[od] = oi
				oneofOrder = append(oneofOrder, oi)
			}
			f.oneof = oi
			f.member = oneofMemberName(fd, oi.class)
			if memberNames[od] == nil {
				memberNames[od] = map[string]string{}
			}
			if err := checkKotlinName(memberNames[od], string(fd.Name()), f.member); err != nil {
				return err
			}
			oi.fields = append(oi.fields, f)
		} else if err := checkKotlinName(emittedNames, string(fd.Name()), f.prop); err != nil {
			return err
		}
		if fd.Cardinality() == protoreflect.Required {
			if len(required) == maxRequired {
				return fmt.Errorf("%s: more than %d required fields are not supported", msg.FullName(), maxRequired)
			}
			f.reqBit = len(required)
			required = append(required, f)
		}
		fields = append(fields, f)
	}

	byNumber := append([]*fieldInfo(nil), fields...)
	sort.SliceStable(byNumber, func(i, j int) bool { return byNumber[i].number() < byNumber[j].number() })

	if err := checkConstructorSlots(msg, fields); err != nil {
		return err
	}

	// The constructor lists a field in declaration order. A oneof takes the place of its first member.
	g.comment(msg)
	g.w.open("public data class %s(", name)
	emitted := map[*oneofInfo]bool{}
	for _, f := range fields {
		if f.oneof != nil {
			if emitted[f.oneof] {
				continue
			}
			emitted[f.oneof] = true
			g.comment(f.oneof.od)
			g.w.line("public val %s: %s.%s? = null,", f.oneof.prop, qualified, f.oneof.class)
			continue
		}
		g.comment(f.fd)
		if f.reqBit >= 0 {
			g.w.line("public val %s: %s,", f.prop, g.propertyType(f))
		} else {
			g.w.line("public val %s: %s = %s,", f.prop, g.propertyType(f), g.propertyDefault(f))
		}
	}
	g.w.line("/** The fields that this version of the schema does not know, kept as encoded bytes. */")
	g.w.line("public val unknownFields: %s = %s.EMPTY,", g.rt("ByteString"), g.rt("ByteString"))
	g.w.close(") : %s {", g.rt("WireMessage"))
	g.w.indent++
	if len(required) > 0 {
		g.w.line("internal var missingRequired: kotlin.Long = 0L")
		g.w.line("")
	}
	hasMethods := false
	for _, f := range fields {
		if f.nullable() {
			g.w.line("public fun has%s(): kotlin.Boolean = this.%s != null", upperFirst(strings.TrimSuffix(f.prop, "_")), f.prop)
			hasMethods = true
		}
	}
	if hasMethods {
		g.w.line("")
	}

	g.sizeMethod(byNumber, qualified)
	g.w.line("")
	g.writeMethod(byNumber, qualified)
	g.w.line("")
	if g.needsRequiredCheck(msg) {
		g.w.open("override fun toByteArray(): kotlin.ByteArray {")
		g.w.line("findMissingRequired()?.let { throw %s(\"missing required field \" + it) }", g.rt("UninitializedMessageException"))
		g.w.line("return %s.encode(this)", g.rt("WireWriter"))
		g.w.close("}")
		g.w.line("")
		g.findMissingRequired(fields, required, qualified)
	} else {
		g.w.line("override fun toByteArray(): kotlin.ByteArray = %s.encode(this)", g.rt("WireWriter"))
	}

	for _, oi := range oneofOrder {
		g.w.line("")
		g.oneofClass(oi, qualified)
	}
	for i := 0; i < enums.Len(); i++ {
		g.w.line("")
		if err := g.enum(enums.Get(i)); err != nil {
			return err
		}
	}
	for i := 0; i < nested.Len(); i++ {
		if nested.Get(i).IsMapEntry() {
			continue
		}
		g.w.line("")
		if err := g.message(nested.Get(i)); err != nil {
			return err
		}
	}

	g.w.line("")
	g.companion(msg, qualified, fields, required)
	g.w.indent--
	g.w.line("}")
	return nil
}

func (g *fileGen) propertyName(fd protoreflect.FieldDescriptor) string {
	name := PropertyName(fd)
	if name == rootFirstSegment(g.root) {
		return name + "_"
	}
	return name
}

func (g *fileGen) oneofPropertyName(od protoreflect.OneofDescriptor) string {
	name := OneofPropertyName(od)
	if name == rootFirstSegment(g.root) {
		return name + "_"
	}
	return name
}

func rootFirstSegment(root string) string {
	return strings.Split(root, ".")[0]
}

func (g *fileGen) requiredFallback(f *fieldInfo) string {
	return g.propertyDefault(f)
}

// maxJVMSlots is the number of parameter slots that a JVM method can take.
const maxJVMSlots = 255

// checkConstructorSlots fails for a message whose constructor does not fit in a JVM method. Every
// field is a parameter with a default, so Kotlin adds one mask parameter for each 32 of them, and a
// 64-bit value takes two slots.
func checkConstructorSlots(msg protoreflect.MessageDescriptor, fields []*fieldInfo) error {
	params, slots := 1, 1 // the unknown fields
	seen := map[*oneofInfo]bool{}
	for _, f := range fields {
		if f.oneof != nil {
			if seen[f.oneof] {
				continue
			}
			seen[f.oneof] = true
		}
		params++
		slots++
		if f.oneof == nil && !f.fd.IsList() && !f.fd.IsMap() && !f.nullable() {
			switch f.fd.Kind() {
			case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
				protoreflect.Uint64Kind, protoreflect.Fixed64Kind, protoreflect.DoubleKind:
				slots++
			}
		}
	}
	// The receiver or the first parameter, the masks, and the marker of the synthetic constructor.
	slots += 2 + (params+31)/32
	if slots > maxJVMSlots {
		return fmt.Errorf("%s: the constructor needs %d parameter slots and the JVM allows %d", msg.FullName(), slots, maxJVMSlots)
	}
	return nil
}

func upperFirst(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func (g *fileGen) oneofClass(oi *oneofInfo, qualified string) {
	g.w.open("public sealed class %s {", oi.class)
	for i, f := range oi.fields {
		if i > 0 {
			g.w.line("")
		}
		g.comment(f.fd)
		g.w.line("public data class %s(public val value: %s) : %s()", f.member, g.elementType(f.fd), oi.class)
	}
	g.w.close("}")
}

// presenceCondition returns the Kotlin condition that decides whether a plain field is written.
func (g *fileGen) presenceCondition(f *fieldInfo, expr string) string {
	fd := f.fd
	if f.reqBit >= 0 {
		return fmt.Sprintf("(this.missingRequired and %dL) == 0L", int64(1)<<f.reqBit)
	}
	if fd.Kind() == protoreflect.EnumKind {
		return expr + ".number != 0"
	}
	switch fd.Kind() {
	case protoreflect.BoolKind:
		return expr
	case protoreflect.FloatKind:
		return expr + ".toRawBits() != 0"
	case protoreflect.DoubleKind:
		return expr + ".toRawBits() != 0L"
	case protoreflect.StringKind:
		return expr + ".isNotEmpty()"
	case protoreflect.BytesKind:
		return "!" + expr + ".isEmpty()"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind,
		protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		return expr + " != 0L"
	}
	return expr + " != 0"
}

func (g *fileGen) sizeMethod(byNumber []*fieldInfo, qualified string) {
	g.w.open("override fun getSerializedSize(): kotlin.Int {")
	g.w.line("var _size = 0")
	for _, f := range byNumber {
		g.sizeField(f, qualified)
	}
	g.w.line("_size += this.unknownFields.size")
	g.w.line("return _size")
	g.w.close("}")
}

// unrecognized returns the Kotlin type of the UNRECOGNIZED class of the enum of a field.
func (g *fileGen) unrecognized(fd protoreflect.FieldDescriptor) string {
	return QualifiedClassName(fd.Enum(), g.root) + ".UNRECOGNIZED"
}

// closedEnum reports whether a field has an enum that drops a number it does not declare. Such a
// number goes to the unknown fields. The number of an open enum stays in the property.
func closedEnum(fd protoreflect.FieldDescriptor) bool {
	return fd.Kind() == protoreflect.EnumKind && fd.Enum().IsClosed()
}

// writeStore writes the statement that stores the value of a field that readValue read, then the
// statement after, which marks the field as read. For a closed enum, a number that the enum does
// not declare goes to the unknown fields instead, and the field stays unread.
func (g *fileGen) writeStore(fd protoreflect.FieldDescriptor, stmt, after string) {
	if !closedEnum(fd) {
		g.w.text(stmt)
		if after != "" {
			g.w.text(after)
		}
		return
	}
	keep := fmt.Sprintf("if (_e is %s) _unknown.addVarint(%d, _n.toLong()) else", g.unrecognized(fd), tagOf(fd.Number(), wireVarint))
	if after == "" {
		g.w.text(keep + " " + stmt)
		return
	}
	g.w.open("%s {", keep)
	g.w.text(stmt)
	g.w.text(after)
	g.w.close("}")
}

func (g *fileGen) sizeField(f *fieldInfo, qualified string) {
	fd := f.fd
	n := fd.Number()
	p := "this." + f.prop
	ws := g.rt("WireSize")
	switch {
	case fd.IsMap():
		entry := fmt.Sprintf("%s + %s", g.sizeCall(fd.MapKey().Kind(), 1, "_k"), g.sizeCall(fd.MapValue().Kind(), 2, "_v"))
		keyFixed, valueFixed := fixedSize(fd.MapKey().Kind()), fixedSize(fd.MapValue().Kind())
		if keyFixed && valueFixed {
			g.w.open("if (%s.isNotEmpty()) {", p)
			g.w.line("val _entry = %s", entry)
			g.w.line("_size += %s.size * (%s.tag(%d) + %s.varint32(_entry) + _entry)", p, ws, n, ws)
			g.w.close("}")
			break
		}
		key, value := "_k", "_v"
		if keyFixed {
			key = "_"
		}
		if valueFixed {
			value = "_"
		}
		g.w.open("for ((%s, %s) in %s) {", key, value, p)
		g.w.line("val _entry = %s", entry)
		g.w.line("_size += %s.tag(%d) + %s.varint32(_entry) + _entry", ws, n, ws)
		g.w.close("}")
	case fd.IsList() && fd.IsPacked():
		g.w.open("if (%s.isNotEmpty()) {", p)
		g.w.line("_size += %s.packed(%d, %s)", ws, n, g.packedPayload(fd.Kind(), p))
		g.w.close("}")
	case fd.IsList() && fixedSize(fd.Kind()):
		g.w.line("_size += %s.size * %s", p, g.sizeCall(fd.Kind(), n, ""))
	case fd.IsList():
		g.w.open("for (_e in %s) {", p)
		g.w.line("_size += %s", g.sizeCall(fd.Kind(), n, "_e"))
		g.w.close("}")
	case f.oneof != nil:
		o := "this." + f.oneof.prop
		cond := fmt.Sprintf("%s is %s", o, f.variant(qualified))
		g.w.line("if (%s) _size += %s", cond, g.sizeCall(fd.Kind(), n, o+".value"))
	case f.nullable():
		cond := p + " != null"
		g.w.line("if (%s) _size += %s", cond, g.sizeCall(fd.Kind(), n, p))
	default:
		g.w.line("if (%s) _size += %s", g.presenceCondition(f, p), g.sizeCall(fd.Kind(), n, p))
	}
}

func (g *fileGen) writeMethod(byNumber []*fieldInfo, qualified string) {
	g.w.open("override fun writeTo(writer: %s) {", g.rt("WireWriter"))
	for _, f := range byNumber {
		g.writeField(f, qualified)
	}
	g.w.line("writer.writeUnknown(this.unknownFields)")
	g.w.close("}")
}

func (g *fileGen) writeField(f *fieldInfo, qualified string) {
	fd := f.fd
	n := fd.Number()
	p := "this." + f.prop
	switch {
	case fd.IsMap():
		g.w.open("for ((_k, _v) in %s) {", p)
		g.w.line("writer.writeTag(%d, %d)", n, wireLength)
		g.w.line("writer.writeVarint32(%s + %s)", g.sizeCall(fd.MapKey().Kind(), 1, "_k"), g.sizeCall(fd.MapValue().Kind(), 2, "_v"))
		g.w.text(writeCall(fd.MapKey().Kind(), 1, "_k"))
		g.w.text(writeCall(fd.MapValue().Kind(), 2, "_v"))
		g.w.close("}")
	case fd.IsList() && fd.IsPacked():
		g.w.open("if (%s.isNotEmpty()) {", p)
		g.w.line("writer.writePacked%s(%d, %s)", packedSuffix(fd.Kind()), n, p)
		g.w.close("}")
	case fd.IsList():
		g.w.open("for (_e in %s) {", p)
		g.w.text(writeCall(fd.Kind(), n, "_e"))
		g.w.close("}")
	case f.oneof != nil:
		o := "this." + f.oneof.prop
		cond := fmt.Sprintf("%s is %s", o, f.variant(qualified))
		g.w.line("if (%s) %s", cond, writeCall(fd.Kind(), n, o+".value"))
	case f.nullable():
		cond := p + " != null"
		g.w.line("if (%s) %s", cond, writeCall(fd.Kind(), n, p))
	default:
		g.w.line("if (%s) %s", g.presenceCondition(f, p), writeCall(fd.Kind(), n, p))
	}
}

// variant returns the qualified class name of a oneof member.
func (f *fieldInfo) variant(qualified string) string {
	return qualified + "." + f.oneof.class + "." + f.member
}

// readValue returns the statements and the expression that read one value of a field.
// With retain, a closed enum reads its number into _n, so that store can keep a number that the
// enum does not declare. A message that may occur again is not read here: see deferred.
func (g *fileGen) readValue(fd protoreflect.FieldDescriptor, retain bool) ([]string, string) {
	switch fd.Kind() {
	case protoreflect.MessageKind:
		return nil, fmt.Sprintf("reader.readMessage(%s)", QualifiedClassName(fd.Message(), g.root))
	case protoreflect.EnumKind:
		enum := QualifiedClassName(fd.Enum(), g.root)
		if !retain || !closedEnum(fd) {
			return nil, fmt.Sprintf("%s.fromNumber(reader.readInt32())", enum)
		}
		return []string{
			"val _n = reader.readInt32()",
			fmt.Sprintf("val _e = %s.fromNumber(_n)", enum),
		}, "_e"
	}
	if fd.Kind() == protoreflect.StringKind && !validatesUTF8(fd) {
		return nil, "reader.readStringLenient()"
	}
	return nil, "reader." + readMethod(fd.Kind()) + "()"
}

// validatesUTF8 reports whether a parse rejects a string field with invalid UTF-8. A map entry
// always does, and so does a field for which protoc Java asks for the check. Other fields follow
// the resolved feature utf8_validation: proto3 verifies, proto2 does not.
func validatesUTF8(fd protoreflect.FieldDescriptor) bool {
	if fd.ContainingMessage().IsMapEntry() || javaUTF8Verify(fd) {
		return true
	}
	if f, ok := fd.(interface{ EnforceUTF8() bool }); ok {
		return f.EnforceUTF8()
	}
	return fd.Syntax() != protoreflect.Proto2
}

func (g *fileGen) companion(msg protoreflect.MessageDescriptor, qualified string, fields, required []*fieldInfo) {
	codec := g.rt("WireCodec")
	g.w.open("public companion object : %s<%s> {", codec, qualified)
	for _, f := range fields {
		if f.hasDeclaredDefault() {
			g.w.line("public val DEFAULT_%s: %s = %s", strings.ToUpper(string(f.fd.Name())), g.elementType(f.fd), g.defaultLiteral(f.fd))
			g.w.line("")
		}
	}
	g.w.line("@kotlin.jvm.JvmStatic")
	if g.needsRequiredCheck(msg) {
		g.w.open("public fun parseFrom(bytes: kotlin.ByteArray): %s {", qualified)
		g.w.line("val _message = decode(%s(bytes))", g.rt("WireReader"))
		g.w.line("_message.findMissingRequired()?.let { throw %s(\"missing required field \" + it) }", g.rt("InvalidWireException"))
		g.w.line("return _message")
		g.w.close("}")
	} else {
		g.w.line("public fun parseFrom(bytes: kotlin.ByteArray): %s = decode(%s(bytes))", qualified, g.rt("WireReader"))
	}
	g.w.line("")
	g.w.open("override fun decodeSections(reader: %s, sections: %s?): %s {", g.rt("WireReader"), g.rt("Sections"), qualified)

	oneofSeen := map[*oneofInfo]bool{}
	var args []string
	for _, f := range fields {
		fd := f.fd
		switch {
		case f.oneof != nil:
			if !oneofSeen[f.oneof] {
				oneofSeen[f.oneof] = true
				g.w.line("var v_%s: %s.%s? = null", f.oneof.prop, qualified, f.oneof.class)
				if oi := f.oneof; oi.hasMessage() {
					g.w.line("var s_%s: %s? = null", oi.prop, g.rt("Sections"))
					g.w.line("var n_%s = 0", oi.prop)
					// A message member that a later member replaces is parsed here, once, so invalid
					// bytes in it are refused as in Java lite.
					g.w.open("fun c_%s() {", oi.prop)
					g.w.line("val _s = s_%s ?: return", oi.prop)
					g.w.open("when (n_%s) {", oi.prop)
					for _, m := range oi.fields {
						if m.fd.Message() != nil {
							g.w.line("%d -> reader.readSections(%s, _s)", m.fd.Number(), QualifiedClassName(m.fd.Message(), g.root))
						}
					}
					g.w.close("}")
					g.w.close("}")
				}
				args = append(args, fmt.Sprintf("%s = v_%s", f.oneof.prop, f.oneof.prop))
			}
		case fd.IsMap():
			g.w.line("val v_%s = kotlin.collections.LinkedHashMap<%s, %s>()", f.prop, g.elementType(fd.MapKey()), g.elementType(fd.MapValue()))
			args = append(args, fmt.Sprintf("%s = java.util.Collections.unmodifiableMap(v_%s)", f.prop, f.prop))
		case fd.IsList():
			g.w.line("val v_%s = kotlin.collections.ArrayList<%s>()", f.prop, g.elementType(fd))
			args = append(args, fmt.Sprintf("%s = java.util.Collections.unmodifiableList(v_%s)", f.prop, f.prop))
		default:
			typ := g.propertyType(f)
			if f.reqBit >= 0 {
				typ += "?"
				g.w.line("var v_%s: %s = null", f.prop, typ)
				if fd.Message() != nil {
					args = append(args, fmt.Sprintf("%s = v_%s ?: throw %s(\"missing required field %s\")", f.prop, f.prop, g.rt("InvalidWireException"), fd.Name()))
				} else {
					args = append(args, fmt.Sprintf("%s = v_%s ?: %s", f.prop, f.prop, g.requiredFallback(f)))
				}
			} else {
				g.w.line("var v_%s: %s = %s", f.prop, typ, g.propertyDefault(f))
				args = append(args, fmt.Sprintf("%s = v_%s", f.prop, f.prop))
			}
			if fd.Message() != nil {
				g.w.line("var s_%s: %s? = null", f.prop, g.rt("Sections"))
			}
		}
	}
	if len(required) > 0 {
		g.w.line("var _missing = %dL", int64(1)<<len(required)-1)
	}
	g.w.line("val _unknown = %s()", g.rt("UnknownFields"))
	g.w.line("var _part = 0")
	g.w.open("while (reader.nextSection(sections, _part++)) {")
	g.w.open("loop@ while (true) {")
	g.w.open("when (val _tag = reader.readTag()) {")
	g.w.line("0 -> break@loop")
	for _, f := range fields {
		g.decodeCase(f, qualified)
	}
	g.w.line("else -> reader.readUnknown(_tag, _unknown)")
	g.w.close("}")
	g.w.close("}")
	g.w.close("}")
	g.dropUnknownMapEnums(fields)
	oneofDone := map[*oneofInfo]bool{}
	for _, f := range fields {
		switch {
		case f.oneof != nil:
			oi := f.oneof
			if oneofDone[oi] || !oi.hasMessage() {
				continue
			}
			oneofDone[oi] = true
			g.w.open("when (n_%s) {", oi.prop)
			for _, m := range oi.fields {
				if m.fd.Message() == nil {
					continue
				}
				g.w.line("%d -> if (s_%s != null) v_%s = %s(reader.readSections(%s, s_%s))", m.fd.Number(), oi.prop, oi.prop, m.variant(qualified), QualifiedClassName(m.fd.Message(), g.root), oi.prop)
			}
			g.w.close("}")
		case !f.fd.IsMap() && !f.fd.IsList() && f.fd.Message() != nil:
			g.w.line("if (s_%s != null) v_%s = reader.readSections(%s, s_%s)", f.prop, f.prop, QualifiedClassName(f.fd.Message(), g.root), f.prop)
		}
	}
	args = append(args, "unknownFields = _unknown.toByteString()")
	if len(required) > 0 {
		g.w.open("val _result = %s(", qualified)
		for _, a := range args {
			g.w.line("%s,", a)
		}
		g.w.close(")")
		g.w.line("_result.missingRequired = _missing")
		g.w.line("return _result")
	} else {
		g.w.open("return %s(", qualified)
		for _, a := range args {
			g.w.line("%s,", a)
		}
		g.w.close(")")
	}
	g.w.close("}")
	g.w.close("}")
}

func (g *fileGen) decodeCase(f *fieldInfo, qualified string) {
	fd := f.fd
	n := fd.Number()
	switch {
	case fd.IsMap():
		g.decodeMap(f)
	case fd.IsList():
		pre, expr := g.readValue(fd, true)
		g.w.open("%d -> {", tagOf(n, wireTypeOf(fd.Kind())))
		for _, l := range pre {
			g.w.text(l)
		}
		g.writeStore(fd, fmt.Sprintf("v_%s.add(%s)", f.prop, expr), "")
		g.w.close("}")
		if isPackable(fd.Kind()) {
			g.w.open("%d -> {", tagOf(n, wireLength))
			g.w.line("val _saved = reader.beginSection()")
			g.w.open("while (!reader.isAtEnd()) {")
			for _, l := range pre {
				g.w.text(l)
			}
			g.writeStore(fd, fmt.Sprintf("v_%s.add(%s)", f.prop, expr), "")
			g.w.close("}")
			g.w.line("reader.endSection(_saved)")
			g.w.close("}")
		}
	case f.oneof != nil:
		variant := f.variant(qualified)
		op := f.oneof.prop
		g.w.open("%d -> {", tagOf(n, wireTypeOf(fd.Kind())))
		switch {
		case fd.Message() != nil:
			g.w.line("val _next = reader.deferMessage(null)")
			g.w.open("if (n_%s != %d) {", op, n)
			g.w.line("c_%s()", op)
			g.w.line("s_%s = null", op)
			g.w.close("}")
			g.w.line("n_%s = %d", op, n)
			g.w.line("s_%s = s_%s?.append(_next) ?: _next", op, op)
			g.w.line("v_%s = null", op)
		default:
			pre, expr := g.readValue(fd, true)
			for _, l := range pre {
				g.w.text(l)
			}
			after := ""
			if f.oneof.hasMessage() {
				after = fmt.Sprintf("c_%s(); n_%s = 0; s_%s = null", op, op, op)
			}
			g.writeStore(fd, fmt.Sprintf("v_%s = %s(%s)", op, variant, expr), after)
		}
		g.w.close("}")
	default:
		g.w.open("%d -> {", tagOf(n, wireTypeOf(fd.Kind())))
		after := ""
		if f.reqBit >= 0 {
			after = fmt.Sprintf("_missing = _missing and %dL", ^(int64(1) << f.reqBit))
		}
		if fd.Message() != nil {
			g.w.line("s_%s = reader.deferMessage(s_%s)", f.prop, f.prop)
			if after != "" {
				g.w.text(after)
			}
		} else {
			pre, expr := g.readValue(fd, true)
			for _, l := range pre {
				g.w.text(l)
			}
			g.writeStore(fd, fmt.Sprintf("v_%s = %s", f.prop, expr), after)
		}
		g.w.close("}")
	}
}

func (g *fileGen) decodeMap(f *fieldInfo) {
	fd := f.fd
	key, val := fd.MapKey(), fd.MapValue()
	n := fd.Number()
	g.w.open("%d -> {", tagOf(n, wireLength))
	g.w.line("val _saved = reader.beginSection()")
	g.w.line("var _key: %s = %s", g.elementType(key), g.defaultLiteral(key))
	if val.Kind() == protoreflect.MessageKind {
		g.w.line("var _value: %s? = null", g.elementType(val))
		g.w.line("var _valueSections: %s? = null", g.rt("Sections"))
	} else {
		g.w.line("var _value: %s = %s", g.elementType(val), g.defaultLiteral(val))
	}
	g.w.open("entry@ while (true) {")
	g.w.open("when (val _t = reader.readTag()) {")
	g.w.line("0 -> break@entry")
	_, keyExpr := g.readValue(key, false)
	g.w.line("%d -> _key = %s", tagOf(1, wireTypeOf(key.Kind())), keyExpr)
	if val.Kind() == protoreflect.MessageKind {
		g.w.open("%d -> {", tagOf(2, wireTypeOf(val.Kind())))
		g.w.line("if (_valueSections != null) reader.readSections(%s, _valueSections)", g.qualifiedValue(val))
		g.w.line("_valueSections = reader.deferMessage(null)")
		g.w.close("}")
	} else {
		_, valExpr := g.readValue(val, false)
		g.w.line("%d -> _value = %s", tagOf(2, wireTypeOf(val.Kind())), valExpr)
	}
	g.w.line("else -> reader.skipField(_t)")
	g.w.close("}")
	g.w.close("}")
	if val.Kind() == protoreflect.MessageKind {
		g.w.line("if (_valueSections != null) _value = reader.readSections(%s, _valueSections)", g.qualifiedValue(val))
	}
	g.w.line("reader.endSection(_saved)")
	switch {
	case val.Kind() == protoreflect.MessageKind && g.needsRequiredCheck(val.Message()):
		g.w.line("v_%s[_key] = _value ?: %s.decode(%s(kotlin.ByteArray(0)))", f.prop, g.elementType(val), g.rt("WireReader"))
	case val.Kind() == protoreflect.MessageKind:
		g.w.line("v_%s[_key] = _value ?: %s()", f.prop, g.elementType(val))
	default:
		g.w.line("v_%s[_key] = _value", f.prop)
	}
	g.w.close("}")
}

// dropUnknownMapEnums moves the entries of a map whose value is an enum number that a closed enum
// does not declare into the unknown fields, after the parse has read every entry. The entries are
// written again in their canonical form, after all other unknown fields, in the order of the map.
func (g *fileGen) dropUnknownMapEnums(fields []*fieldInfo) {
	var maps []*fieldInfo
	for _, f := range fields {
		if f.fd.IsMap() && closedEnum(f.fd.MapValue()) {
			maps = append(maps, f)
		}
	}
	sort.SliceStable(maps, func(i, j int) bool { return maps[i].number() < maps[j].number() })
	for _, f := range maps {
		key, val := f.fd.MapKey(), f.fd.MapValue()
		g.w.open("run {")
		g.w.line("val _it = v_%s.entries.iterator()", f.prop)
		g.w.open("while (_it.hasNext()) {")
		g.w.line("val _entry = _it.next()")
		g.w.open("if (_entry.value is %s) {", g.unrecognized(val))
		g.w.line("val _k = _entry.key")
		g.w.line("val _v = _entry.value")
		g.w.line("val writer = %s(kotlin.ByteArray(%s + %s))", g.rt("WireWriter"), g.sizeCall(key.Kind(), 1, "_k"), g.sizeCall(val.Kind(), 2, "_v"))
		g.w.text(writeCall(key.Kind(), 1, "_k"))
		g.w.text(writeCall(val.Kind(), 2, "_v"))
		g.w.line("_unknown.addLengthDelimited(%d, writer.toByteArray())", f.fd.Number())
		g.w.line("_it.remove()")
		g.w.close("}")
		g.w.close("}")
		g.w.close("}")
	}
}

// qualifiedValue returns the codec expression of a message.
func (g *fileGen) qualifiedValue(fd protoreflect.FieldDescriptor) string {
	return QualifiedClassName(fd.Message(), g.root)
}

// maxRequired is the number of required fields of one message that the missing-required mask holds.
const maxRequired = 63

// findMissingRequired writes the method that returns the name of the first required field that a
// parse did not read, in this message or in a message below it. It returns null if none is missing.
func (g *fileGen) findMissingRequired(fields, required []*fieldInfo, qualified string) {
	g.w.open("internal fun findMissingRequired(): kotlin.String? {")
	for _, f := range required {
		g.w.line("if ((this.missingRequired and %dL) != 0L) return %q", int64(1)<<f.reqBit, string(f.fd.Name()))
	}
	for _, f := range fields {
		fd := f.fd
		name := string(fd.Name())
		p := "this." + f.prop
		switch {
		case fd.IsMap():
			if value := fd.MapValue().Message(); value != nil && g.needsRequiredCheck(value) {
				g.w.open("for ((_k, _v) in %s) {", p)
				g.w.line("_v.findMissingRequired()?.let { return %q + it }", name+".")
				g.w.close("}")
			}
		case fd.Message() == nil || !g.needsRequiredCheck(fd.Message()):
		case fd.IsList():
			g.w.open("for (_e in %s) {", p)
			g.w.line("_e.findMissingRequired()?.let { return %q + it }", name+".")
			g.w.close("}")
		case f.oneof != nil:
			o := "this." + f.oneof.prop
			g.w.line("if (%s is %s) %s.value.findMissingRequired()?.let { return %q + it }", o, f.variant(qualified), o, name+".")
		default:
			if f.reqBit >= 0 {
				g.w.line("%s.findMissingRequired()?.let { return %q + it }", p, name+".")
			} else {
				g.w.line("%s?.findMissingRequired()?.let { return %q + it }", p, name+".")
			}
		}
	}
	g.w.line("return null")
	g.w.close("}")
}

// needsRequiredCheck reports whether a message has a required field, or has a field whose message
// has one. A parse of such a message checks the required fields once, after it has merged all parts.
func (g *fileGen) needsRequiredCheck(msg protoreflect.MessageDescriptor) bool {
	if g.needsCheck == nil {
		g.needsCheck = map[protoreflect.FullName]bool{}
	}
	if known, ok := g.needsCheck[msg.FullName()]; ok {
		return known
	}
	// Collect the messages below msg, then spread the flag from the messages with a required field
	// to the messages that contain them. A loop of messages needs no special case.
	reach := map[protoreflect.FullName]protoreflect.MessageDescriptor{}
	var visit func(m protoreflect.MessageDescriptor)
	visit = func(m protoreflect.MessageDescriptor) {
		if _, ok := reach[m.FullName()]; ok {
			return
		}
		reach[m.FullName()] = m
		for i := 0; i < m.Fields().Len(); i++ {
			if sub := m.Fields().Get(i).Message(); sub != nil {
				visit(sub)
			}
		}
	}
	visit(msg)
	for name, m := range reach {
		for i := 0; i < m.Fields().Len(); i++ {
			if m.Fields().Get(i).Cardinality() == protoreflect.Required {
				g.needsCheck[name] = true
			}
		}
	}
	for changed := true; changed; {
		changed = false
		for name, m := range reach {
			if g.needsCheck[name] {
				continue
			}
			for i := 0; i < m.Fields().Len(); i++ {
				if sub := m.Fields().Get(i).Message(); sub != nil && g.needsCheck[sub.FullName()] {
					g.needsCheck[name] = true
					changed = true
					break
				}
			}
		}
	}
	for name := range reach {
		if !g.needsCheck[name] {
			g.needsCheck[name] = false
		}
	}
	return g.needsCheck[msg.FullName()]
}
