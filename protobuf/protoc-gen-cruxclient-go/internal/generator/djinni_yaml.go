// GenerateDjinniYAML generates the .djinni.yaml file for a proto file descriptor.
// The output is functionally equivalent to the C++ plugin's api_generator.cc
// GenerateDjinniYAML function. It produces one YAML record per
// message (including nested), skipping map-entry synthetics.
//
// When options enable the Swift output, each record also has swift: and swiftxx: blocks.
// When options enable the Kotlin output, the jni: block has the keys of the Kotlin
// translator and the kotlin: block has jniTypename.
func GenerateDjinniYAML(rw protoplugin.ResponseWriter, fileDesc protoreflect.FileDescriptor, options Options) {
	w := codegen.NewWriter()

	path := string(fileDesc.Path())
	baseName := common.StripProto(path)

	// Path segments for name derivation
	paths := common.Tokenize(common.StripProto(path), "/")
	dirParts := paths[:len(paths)-1]
	dir := strings.Join(dirParts, "_")

	// Domain name: paths[1] if paths[0]=="s12", else paths[0]
	domainName := paths[0]
	if paths[0] == "s12" && len(paths) > 1 {
		domainName = paths[1]
	}

	fileNameCamel := common.ToCamelCase(paths[len(paths)-1])
	mainFileName := baseName

	// Proto file options
	opts := fileDesc.Options().(*descriptorpb.FileOptions)
	javaPackage := opts.GetJavaPackage()
	objcClassPrefix := opts.GetObjcClassPrefix()
	wirePackage := common.GetWirePackage(fileDesc)

	// Comment header
	w.WL("# This file is generated by s12-proto api generator. Please DO NOT modify.")

	// Per-message YAML records
	messages := common.GetMessagesFromFile(fileDesc)
	for _, msg := range messages {
		if msg.IsMapEntry() {
			continue
		}

		messageName := common.ClassName(msg, false)
		cppTypeName := common.DotsToColons(string(msg.FullName()))
		javaMessageBoxName := common.UnderscoresToDots(messageName)
		javaMessageName := common.UnderscoresToDollar(messageName)
		javaPackageSlashes := common.DotsToSlashs(javaPackage)

		var swift *swiftYAML
		if options.SwiftEnabled() {
			swift = &swiftYAML{
				module:        common.SwiftProtobufModule(fileDesc, options.SwiftModule),
				prefix:        common.SwiftProtobufPrefix(fileDesc),
				typeName:      common.SwiftProtobufTypeName(msg),
				translator:    swiftxxTranslatorName(cppTypeName),
				translatorHdr: baseName + swiftxxHeaderSuffix,
			}
		}

		var kotlin *kotlinYAML
		if options.KotlinEnabled() {
			kotlin = &kotlinYAML{
				typename:      common.KotlinQualifiedName(msg, options.KotlinPackage),
				typeSignature: "L" + common.KotlinBinaryName(msg, options.KotlinPackage) + ";",
				translator:    kotlinJNITranslatorName(cppTypeName),
				translatorHdr: baseName + kotlinJNIHeaderSuffix,
			}
		}

		writeDjinniYAMLRecord(w, domainName, fileNameCamel, dir, baseName, mainFileName,
			messageName, cppTypeName, javaMessageBoxName, javaMessageName,
			javaPackageSlashes, javaPackage, objcClassPrefix, wirePackage, swift, kotlin)
	}

	rw.AddFile(baseName+".djinni.yaml", w.String())
}

// swiftYAML holds the values of the swift: and swiftxx: blocks of one record.
type swiftYAML struct {
	module        string
	prefix        string
	typeName      string
	translator    string
	translatorHdr string
}

// kotlinYAML holds the values of the pure Kotlin class in the jni: and kotlin: blocks of one record.
type kotlinYAML struct {
	typename      string
	typeSignature string
	translator    string
	translatorHdr string
}

// writeDjinniYAMLRecord writes a single YAML record for a message.
// A nil swift leaves out the swift: and swiftxx: blocks. A nil kotlin leaves out the Kotlin keys.
func writeDjinniYAMLRecord(w *codegen.CodeWriter,
	domainName, fileNameCamel, dir, baseName, mainFileName,
	messageName, cppTypeName, javaMessageBoxName, javaMessageName,
	javaPackageSlashes, javaPackage, objcClassPrefix, wirePackage string,
	swift *swiftYAML, kotlin *kotlinYAML) {

	w.WL("---")
	w.WL("name: pb_%s_%s_%s", domainName, fileNameCamel, messageName)
	w.WL("typedef: 'record deriving(eq, ord, parcelable)'")
	w.WL("params: []")
	w.WL("prefix: 'pb'")

	w.WL("cpp:")
	w.WL("  typename: '%s'", cppTypeName)
	w.WL("  header: '\"%s.pb.h\"'", baseName)
	w.WL("  byValue: false")

	w.WL("objc:")
	w.WL("  typename: '%s%s'", objcClassPrefix, messageName)
	w.WL("  header: '\"%s_%s.pbobjc.h\"'", dir, fileNameCamel)
	w.WL("  boxed: '%s%s'", objcClassPrefix, messageName)
	w.WL("  pointer: true")
	w.WL("  hash: '%s.hash()'")

	w.WL("objcpp:")
	w.WL("  translator: 'djinni::%s::Translator'", cppTypeName)
	w.WL("  header: '\"%s.djinni.objc.h\"'", mainFileName)

	w.WL("java:")
	w.WL("  typename: '%s.%s'", javaPackage, javaMessageBoxName)
	w.WL("  boxed: '%s.%s'", javaPackage, javaMessageBoxName)
	w.WL("  reference: true")
	w.WL("  generic: false")
	w.WL("  hash: '%s.hashCode()'")

	w.WL("jni:")
	w.WL("  translator: 'djinni::%s::Translator'", cppTypeName)
	w.WL("  header: '\"%s.djinni.jni.h\"'", mainFileName)
	w.WL("  typename: jobject")
	w.WL("  typeSignature: 'L%s/%s;'", javaPackageSlashes, javaMessageName)
	if kotlin != nil {
		w.WL("  kotlinTranslator: '%s'", kotlin.translator)
		w.WL("  kotlinHeader: '\"%s\"'", kotlin.translatorHdr)
		w.WL("  kotlinTypeSignature: '%s'", kotlin.typeSignature)
	}

	if swift != nil {
		w.WL("swift:")
		w.WL("  typename: '%s'", swift.typeName)
		w.WL("  module: '%s'", swift.module)
		w.WL("  prefix: '%s'", swift.prefix)
		w.WL("  generic: false")
		w.WL("  translator: 'ProtobufMarshaller<%s>'", swift.typeName)
		w.WL("  translator.module: 'DjinniSupport'")
		w.WL("swiftxx:")
		w.WL("  translator: '%s'", swift.translator)
		w.WL("  header: '\"%s\"'", swift.translatorHdr)
	}

	if wirePackage != "" || kotlin != nil {
		w.WL("kotlin:")
		if wirePackage != "" {
			w.WL("  typename: '%s.%s'", wirePackage, javaMessageBoxName)
			w.WL("  isProtobufMessage: true")
		}
		if kotlin != nil {
			w.WL("  jniTypename: '%s'", kotlin.typename)
		}
	}
	w.WL()
}
