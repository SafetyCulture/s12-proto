package generator

import (
	"github.com/bufbuild/protoplugin"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/SafetyCulture/s12-proto/protobuf/protoc-gen-cruxclient-go/internal/codegen"
	"github.com/SafetyCulture/s12-proto/protobuf/protoc-gen-cruxclient-go/internal/common"
)

const swiftxxHeaderSuffix = ".djinni.swiftxx.h"

// swiftxxTranslatorName returns the translator type of a message. It has its own
// namespace because the ObjC translator of the same message is in djinni::<type>.
func swiftxxTranslatorName(cppTypeName string) string {
	return "djinni::swift::" + cppTypeName + "::Translator"
}

// GenerateDjinniSwiftxx generates the .djinni.swiftxx.h file for a proto file descriptor.
// It writes one Translator for each message, nested messages included. It skips map entries.
// Each Translator moves a message as serialized bytes.
func GenerateDjinniSwiftxx(rw protoplugin.ResponseWriter, fileDesc protoreflect.FileDescriptor) {
	w := codegen.NewWriter()

	baseName := common.StripProto(string(fileDesc.Path()))

	w.WL("// This file is generated by s12-proto api generator. Please DO NOT modify.")
	w.WL("#pragma once")
	w.WL("#include \"djinni_support.hpp\"")
	w.WL("#include \"%s.pb.h\"", baseName)
	w.WL("#include <cstddef>")
	w.WL("#include <limits>")
	w.WL("#include <string>")
	w.WL("#include <utility>")
	w.WL("#include <variant>")
	w.WL()

	for _, msg := range common.GetMessagesFromFile(fileDesc) {
		if msg.IsMapEntry() {
			continue
		}

		writeDjinniSwiftxxBlock(w, cppQualifiedName(msg.FullName()))
	}

	rw.AddFile(baseName+swiftxxHeaderSuffix, w.String())
}

// writeDjinniSwiftxxBlock writes a single Swift Translator block for a message. The djinni
// names are fully qualified, because a message in the package "swift" with the name of a
// djinni type would open a namespace that hides it. Both directions throw ErrorValue, which
// the generated glue turns into a Swift error, also for a message inside a record or a list.
func writeDjinniSwiftxxBlock(w *codegen.CodeWriter, cppTypeName string) {
	w.WL("namespace djinni::swift::%s {", cppTypeName)
	w.WL("struct Translator {")
	w.WL("  using CppType = ::%s;", cppTypeName)
	w.WL()

	w.WL("  static CppType toCpp(const ::djinni::swift::AnyValue& value) {")
	w.WL("    const auto& bytes = ::std::get<::djinni::swift::BinaryValue>(value);")
	w.WL("    CppType cpp_message;")
	w.WL("    if (bytes.size() > static_cast<::std::size_t>(::std::numeric_limits<int>::max()) ||")
	w.WL("        !cpp_message.ParseFromArray(bytes.data(), static_cast<int>(bytes.size()))) {")
	w.WL("      throw ::djinni::swift::ErrorValue(::std::string(\"failed to parse protobuf type \") + ::std::string(cpp_message.GetTypeName()));")
	w.WL("    }")
	w.WL("    return cpp_message;")
	w.WL("  }")
	w.WL()

	w.WL("  static ::djinni::swift::AnyValue fromCpp(const CppType& message) {")
	w.WL("    if (!message.IsInitialized()) {")
	w.WL("      throw ::djinni::swift::ErrorValue(::std::string(\"failed to serialize protobuf type \") +")
	w.WL("          ::std::string(message.GetTypeName()) + \": \" + message.InitializationErrorString());")
	w.WL("    }")
	w.WL("    const ::std::size_t size = message.ByteSizeLong();")
	w.WL("    if (size > static_cast<::std::size_t>(::std::numeric_limits<int>::max())) {")
	w.WL("      throw ::djinni::swift::ErrorValue(::std::string(\"failed to serialize protobuf type \") + ::std::string(message.GetTypeName()));")
	w.WL("    }")
	w.WL("    ::djinni::swift::BinaryValue bytes(size);")
	w.WL("    if (message.SerializeWithCachedSizesToArray(bytes.data()) != bytes.data() + size) {")
	w.WL("      throw ::djinni::swift::ErrorValue(::std::string(\"failed to serialize protobuf type \") + ::std::string(message.GetTypeName()));")
	w.WL("    }")
	w.WL("    return {::std::move(bytes)};")
	w.WL("  }")

	w.WL("};")
	w.WL("}  //namespace djinni::swift::%s", cppTypeName)
	w.WL()
}
