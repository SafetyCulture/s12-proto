package generator

import (
	"github.com/bufbuild/protoplugin"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/SafetyCulture/s12-proto/protobuf/protoc-gen-cruxclient-go/internal/codegen"
	"github.com/SafetyCulture/s12-proto/protobuf/protoc-gen-cruxclient-go/internal/common"
)

const swiftxxHeaderSuffix = ".djinni.swiftxx.h"

// swiftxxTranslatorName returns the translator type of a message. It has its own
// namespace because the ObjC translator of the same message is in djinni::<type>.
func swiftxxTranslatorName(cppTypeName string) string {
	return "djinni::swift::" + cppTypeName + "::Translator"
}

// GenerateDjinniSwiftxx generates the .djinni.swiftxx.h file for a proto file descriptor.
// It writes one Translator for each message, nested messages included. It skips map entries.
// Each Translator moves a message as serialized bytes.
func GenerateDjinniSwiftxx(rw protoplugin.ResponseWriter, fileDesc protoreflect.FileDescriptor) {
	w := codegen.NewWriter()

	baseName := common.StripProto(string(fileDesc.Path()))

	w.WL("// This file is generated by s12-proto api generator. Please DO NOT modify.")
	w.WL("#pragma once")
	w.WL("#include \"djinni_support.hpp\"")

	for _, msg := range common.GetMessagesFromFile(fileDesc) {
		if msg.IsMapEntry() {
			continue
		}

		writeDjinniSwiftxxBlock(w, baseName, common.DotsToColons(string(msg.FullName())))
	}

	rw.AddFile(baseName+swiftxxHeaderSuffix, w.String())
}

// writeDjinniSwiftxxBlock writes a single Swift Translator block for a message.
func writeDjinniSwiftxxBlock(w *codegen.CodeWriter, baseName, cppTypeName string) {
	w.WL("#include \"%s.pb.h\"", baseName)
	w.WL()
	w.WL("namespace djinni::swift::%s {", cppTypeName)
	w.WL("struct Translator {")
	w.WL("  using CppType = ::%s;", cppTypeName)
	w.WL()

	w.WL("  static CppType toCpp(const AnyValue& value) {")
	w.WL("    const auto& bytes = std::get<BinaryValue>(value);")
	w.WL("    CppType cpp_message;")
	w.WL("    if (!cpp_message.ParseFromArray(bytes.data(), static_cast<int>(bytes.size()))) {")
	w.WL("      throw ErrorValue(std::string(\"failed to parse protobuf type \") + std::string(cpp_message.GetTypeName()));")
	w.WL("    }")
	w.WL("    return cpp_message;")
	w.WL("  }")
	w.WL()

	w.WL("  static AnyValue fromCpp(const CppType& message) {")
	w.WL("    BinaryValue bytes(message.ByteSizeLong());")
	w.WL("    if (!message.SerializeToArray(bytes.data(), static_cast<int>(bytes.size()))) {")
	w.WL("      return ErrorValue(std::string(\"failed to serialize protobuf type \") + std::string(message.GetTypeName()));")
	w.WL("    }")
	w.WL("    return {bytes};")
	w.WL("  }")

	w.WL("};")
	w.WL("}  //namespace djinni::swift::%s", cppTypeName)
	w.WL()
}
