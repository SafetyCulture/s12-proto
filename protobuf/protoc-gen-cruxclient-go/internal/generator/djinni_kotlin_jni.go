package generator

import (
	"github.com/bufbuild/protoplugin"
	"google.golang.org/protobuf/reflect/protoreflect"

	"github.com/SafetyCulture/s12-proto/protobuf/protoc-gen-cruxclient-go/internal/codegen"
	"github.com/SafetyCulture/s12-proto/protobuf/protoc-gen-cruxclient-go/internal/common"
)

const kotlinJNIHeaderSuffix = ".djinni.kotlin.jni.h"

// kotlinJNITranslatorName returns the JNI translator type of the pure Kotlin class of a
// message. It has its own namespace because the translator of the Java class of the same
// message is in djinni::<type>, and an Android binary has both.
func kotlinJNITranslatorName(cppTypeName string) string {
	return "djinni::kotlin::" + cppTypeName + "::Translator"
}

// GenerateDjinniKotlinJNI generates the .djinni.kotlin.jni.h file for a proto file descriptor.
// It has the structure of GenerateDjinniJNI and binds the pure Kotlin classes.
func GenerateDjinniKotlinJNI(rw protoplugin.ResponseWriter, fileDesc protoreflect.FileDescriptor, options Options) {
	w := codegen.NewWriter()

	baseName := common.StripProto(string(fileDesc.Path()))

	w.WL("// This file is generated by s12-proto api generator. Please DO NOT modify.")
	w.WL("#pragma once")
	w.WL("#include \"djinni_support.hpp\"")
	w.WL("#include \"%s.pb.h\"", baseName)
	w.WL("#include <limits>")
	w.WL("#include <memory>")
	w.WL("#include <stdexcept>")
	w.WL("#include <string>")
	w.WL()

	for _, msg := range common.GetMessagesFromFile(fileDesc) {
		if msg.IsMapEntry() {
			continue
		}

		writeDjinniKotlinJNIBlock(w, common.DotsToColons(string(msg.FullName())),
			common.KotlinBinaryName(msg, options.KotlinPackage))
	}

	rw.AddFile(baseName+kotlinJNIHeaderSuffix, w.String())
}

// writeDjinniKotlinJNIBlock writes a single JNIInfo and Translator block for a message.
// The djinni names are fully qualified, because a message in the package "kotlin" with the
// name of a djinni type would open a namespace that hides it.
func writeDjinniKotlinJNIBlock(w *codegen.CodeWriter, cppTypeName, binaryName string) {
	w.WL("namespace djinni::kotlin::%s {", cppTypeName)

	w.WL("struct JNIInfo {")
	w.WL("  const ::djinni::GlobalRef<jclass> clazz { ::djinni::jniFindClass(\"%s\") };", binaryName)
	w.WL("  const jmethodID method_toBytes { ::djinni::jniGetMethodID(clazz.get(), \"toByteArray\", \"()[B\") };")
	w.WL("  const jmethodID method_fromBytes { ::djinni::jniGetStaticMethodID(clazz.get(), \"parseFrom\", \"([B)L%s;\") };", binaryName)
	w.WL("};")
	w.WL()

	w.WL("struct Translator {")
	w.WL("  using CppType = ::%s;", cppTypeName)
	w.WL("  using JniType = jobject;")
	w.WL("  using Boxed = Translator;")
	w.WL()

	w.WL("  static CppType toCpp(JNIEnv* jniEnv, JniType j) {")
	w.WL("    assert(j != nullptr);")
	w.WL("    const auto& data = ::djinni::JniClass<JNIInfo>::get();")
	w.WL("    assert(jniEnv->IsInstanceOf(j, data.clazz.get()));")
	w.WL("    ::djinni::LocalRef<jbyteArray> byteArray { static_cast<jbyteArray>(jniEnv->CallObjectMethod(j, data.method_toBytes)) };")
	w.WL("    ::djinni::jniExceptionCheck(jniEnv);")
	w.WL("    const jsize byte_len = jniEnv->GetArrayLength(byteArray.get());")
	w.WL("    auto release = [&](jbyte* elements) { jniEnv->ReleaseByteArrayElements(byteArray.get(), elements, JNI_ABORT); };")
	w.WL("    const std::unique_ptr<jbyte, decltype(release)> byte { jniEnv->GetByteArrayElements(byteArray.get(), nullptr), release };")
	w.WL("    ::djinni::jniExceptionCheck(jniEnv);")
	w.WL("    CppType cpp_message;")
	w.WL("    if (byte == nullptr || !cpp_message.ParseFromArray(byte.get(), byte_len)) {")
	w.WL("      throw std::runtime_error(std::string(\"failed to parse protobuf type \") + std::string(cpp_message.GetTypeName()));")
	w.WL("    }")
	w.WL("    return cpp_message;")
	w.WL("  }")
	w.WL()

	w.WL("  static ::djinni::LocalRef<JniType> fromCpp(JNIEnv* jniEnv, const CppType& message) {")
	w.WL("    std::string buffer;")
	w.WL("    if (!message.SerializeToString(&buffer) || buffer.size() > static_cast<size_t>(std::numeric_limits<jsize>::max())) {")
	w.WL("      throw std::runtime_error(std::string(\"failed to serialize protobuf type \") + std::string(message.GetTypeName()));")
	w.WL("    }")
	w.WL("    const auto size = static_cast<jsize>(buffer.size());")
	w.WL("    ::djinni::LocalRef<jbyteArray> bytes { jniEnv->NewByteArray(size) };")
	w.WL("    ::djinni::jniExceptionCheck(jniEnv);")
	w.WL("    jniEnv->SetByteArrayRegion(bytes.get(), 0, size, reinterpret_cast<const jbyte*>(buffer.data()));")
	w.WL("    ::djinni::jniExceptionCheck(jniEnv);")
	w.WL("    const auto& data = ::djinni::JniClass<JNIInfo>::get();")
	w.WL("    ::djinni::LocalRef<JniType> j { jniEnv->CallStaticObjectMethod(data.clazz.get(), data.method_fromBytes, bytes.get()) };")
	w.WL("    ::djinni::jniExceptionCheck(jniEnv);")
	w.WL("    return j;")
	w.WL("  }")

	w.WL("};")
	w.WL("}  //namespace djinni::kotlin::%s", cppTypeName)
	w.WL()
}
