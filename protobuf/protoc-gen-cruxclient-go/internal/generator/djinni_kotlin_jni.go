const kotlinJNIHeaderSuffix = ".djinni.kotlin.jni.h"

// kotlinJNITranslatorName returns the JNI translator type of the pure Kotlin class of a
// message. It has its own namespace because the translator of the Java class of the same
// message is in djinni::<type>, and an Android binary has both.
func kotlinJNITranslatorName(cppTypeName string) string {
	return "djinni::kotlin::" + cppTypeName + "::Translator"
}

// GenerateDjinniKotlinJNI generates the .djinni.kotlin.jni.h file for a proto file descriptor.
// It has the structure of GenerateDjinniJNI and binds the pure Kotlin classes.
func GenerateDjinniKotlinJNI(rw protoplugin.ResponseWriter, fileDesc protoreflect.FileDescriptor, options Options) {
	w := codegen.NewWriter()

	baseName := common.StripProto(string(fileDesc.Path()))

	w.WL("// This file is generated by s12-proto api generator. Please DO NOT modify.")
	w.WL("#pragma once")
	w.WL("#include \"djinni_support.hpp\"")

	for _, msg := range common.GetMessagesFromFile(fileDesc) {
		if msg.IsMapEntry() {
			continue
		}

		writeDjinniKotlinJNIBlock(w, baseName, common.DotsToColons(string(msg.FullName())),
			common.KotlinBinaryName(msg, options.KotlinPackage))
	}

	rw.AddFile(baseName+kotlinJNIHeaderSuffix, w.String())
}

// writeDjinniKotlinJNIBlock writes a single JNIInfo and Translator block for a message.
func writeDjinniKotlinJNIBlock(w *codegen.CodeWriter, baseName, cppTypeName, binaryName string) {
	w.WL("#include \"%s.pb.h\"", baseName)
	w.WL("namespace djinni::kotlin::%s {", cppTypeName)

	w.WL("struct JNIInfo {")
	w.WL("  const GlobalRef<jclass> clazz { jniFindClass(\"%s\")  };", binaryName)
	w.WL("  const jmethodID method_toBytes { jniGetMethodID(clazz.get(), \"toByteArray\", \"()[B\") };")
	w.WL("  const jmethodID method_byteSize { jniGetMethodID(clazz.get(), \"getSerializedSize\", \"()I\") };")
	w.WL("  const jmethodID method_fromBytes { jniGetStaticMethodID(clazz.get(), \"parseFrom\", \"([B)L%s;\") };", binaryName)
	w.WL("};")
	w.WL()

	w.WL("struct Translator {")
	w.WL("  using CppType = ::%s;", cppTypeName)
	w.WL("  using JniType = jobject;")
	w.WL("  using Boxed = Translator;")
	w.WL()

	w.WL("  static CppType toCpp(JNIEnv* jniEnv, JniType j) {")
	w.WL("    assert(j != nullptr);")
	w.WL("    const auto& data = JniClass<JNIInfo>::get();")
	w.WL("    assert(jniEnv->IsInstanceOf(j, data.clazz.get()));")
	w.WL("    jbyteArray byteArray = static_cast<jbyteArray>(jniEnv->CallObjectMethod(j, data.method_toBytes));")
	w.WL("    auto byte_len = jniEnv->CallIntMethod(j, data.method_byteSize);")
	w.WL("    jbyte* byte = jniEnv->GetByteArrayElements(byteArray, NULL);")
	w.WL("    CppType cpp_message;")
	w.WL("    cpp_message.ParseFromArray(byte, byte_len);")
	w.WL("    jniEnv->ReleaseByteArrayElements(byteArray, byte, JNI_ABORT);")
	w.WL("    jniExceptionCheck(jniEnv);")
	w.WL("    return cpp_message;")
	w.WL("  }")
	w.WL()

	w.WL("  static LocalRef<JniType> fromCpp(JNIEnv* jniEnv, const CppType& message) {")
	w.WL("    size_t size = message.ByteSizeLong();")
	w.WL("    jbyte* temp = new jbyte[size];")
	w.WL("    message.SerializeToArray(temp, static_cast<int>(size));")
	w.WL("    jbyteArray bytes = jniEnv->NewByteArray(size);")
	w.WL("    jniEnv->SetByteArrayRegion(bytes, 0, size, temp);")
	w.WL("    delete[] temp;")
	w.WL("    const auto& data = JniClass<JNIInfo>::get();")
	w.WL("    auto j = LocalRef<JniType>{jniEnv->CallStaticObjectMethod(data.clazz.get(), data.method_fromBytes, bytes)};")
	w.WL("    jniExceptionCheck(jniEnv);")
	w.WL("    return j;")
	w.WL("  }")

	w.WL("};")
	w.WL("}  //namespace djinni::kotlin::%s", cppTypeName)
	w.WL()
}
