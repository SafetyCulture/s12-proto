package swift

import (
	"fmt"
	"strings"
)

const compatibilityVersion = 2

// generateFile returns the text of the Swift file of one proto file.
func (g *generator) generateFile(f *file) (string, error) {
	prefix := f.swiftPrefix()
	if prefix != nil && *prefix != "" && !isValidSwiftIdentifier(*prefix) {
		return "", fmt.Errorf("%s has an 'swift_prefix' that isn't a valid Swift identifier (%s)", f.name, *prefix)
	}
	g.namer = newNamer(g.opts.swiftProtobufModule, f)
	g.extensions = g.newExtensionSet(f)
	p := newPrinter()
	rt := g.namer.runtimePrefix()
	runtimeModule := g.namer.runtimeModule

	p.print("// DO NOT EDIT.\n// swift-format-ignore-file\n// swiftlint:disable all\n//\n// Generated by the Swift generator plugin for the protocol buffer compiler.\n// Source: " + f.name + "\n//\n// For information on using the generated types, please see the documentation:\n//   https://github.com/apple/swift-protobuf/\n")

	if !g.opts.stripNonfunctionalCodegen {
		loc := f.location(filePathEdition)
		if loc == nil {
			loc = f.location(filePathSyntax)
		}
		if loc != nil {
			detached := "//"
			comments := asSourceComment(loc, "///", &detached)
			if comments != "" {
				if strings.HasSuffix(comments, "\n\n") {
					p.printNoNewline(comments)
				} else {
					p.print(comments)
				}
			}
		}
	}

	fileDefinesTypes := len(f.enums) > 0 || len(f.messages) > 0 || len(f.extensions) > 0
	snippet := g.opts.importDirective
	hasImports := false
	if f.needsFoundationImport() {
		p.print(fmt.Sprintf("#if canImport(FoundationEssentials)\n%s FoundationEssentials\n#else\n%s Foundation\n#endif", snippet, snippet))
		hasImports = true
	}
	if f.isBundledProto() {
		p.print(fmt.Sprintf("// 'import %s' suppressed, this proto file is meant to be bundled in the runtime.", runtimeModule))
		hasImports = true
	} else if fileDefinesTypes {
		p.print(snippet + " " + runtimeModule)
		hasImports = true
	}

	if !fileDefinesTypes {
		if hasImports {
			p.print()
		}
		p.print("// This file contained no messages, enums, or extensions.")
		return p.String(), nil
	}

	p.print()
	g.generateVersionCheck(p, rt)

	enums := make([]*enumGen, 0, len(f.enums))
	messages := make([]*messageGen, 0, len(f.messages))
	g.extensions.add(f.extensions)
	for _, e := range f.enums {
		enums = append(enums, g.newEnumGen(e))
	}
	for _, m := range f.messages {
		messages = append(messages, g.newMessageGen(m))
	}

	for _, e := range enums {
		e.generateMainEnum(p)
	}
	for _, m := range messages {
		if err := m.generateMainStruct(p); err != nil {
			return "", err
		}
	}

	if !g.extensions.isEmpty() {
		_, base, suffix := splitPath(f.name)
		p.print("", "// MARK: - Extension support defined in "+base+suffix+".")
		g.extensions.generateMessageSwiftExtensions(p)
		g.extensions.generateFileProtobufExtensionRegistry(p)
		g.extensions.generateProtobufExtensionDeclarations(p)
	}

	needsProtoPackage := f.pkg != "" && len(messages) > 0
	if needsProtoPackage || len(enums) > 0 || len(messages) > 0 {
		p.print("", "// MARK: - Code below here is support for the SwiftProtobuf runtime.")
		if needsProtoPackage && !g.opts.hides(hiddenTypes) {
			p.print("", fmt.Sprintf("fileprivate nonisolated let _protobuf_package = \"%s\"", f.pkg))
		}
		for _, e := range enums {
			e.generateRuntimeSupport(p)
		}
		for _, m := range messages {
			m.generateRuntimeSupport(p, nil)
		}
	}
	return p.String(), nil
}

func (g *generator) generateVersionCheck(p *printer, rt string) {
	v := compatibilityVersion
	p.print(fmt.Sprintf("// If the compiler emits an error on this type, it is because this file\n"+
		"// was generated by a version of the `protoc` Swift plug-in that is\n"+
		"// incompatible with the version of SwiftProtobuf to which you are linking.\n"+
		"// Please ensure that you are building against the same version of the API\n"+
		"// that was used to generate this file.\n"+
		"fileprivate nonisolated struct _GeneratedWithProtocGenSwiftVersion: %sProtobufAPIVersionCheck {", rt))
	p.printIndented(
		fmt.Sprintf("struct _%d: %sProtobufAPIVersion_%d {}", v, rt, v),
		fmt.Sprintf("typealias Version = _%d", v),
	)
	p.print("}")
}
